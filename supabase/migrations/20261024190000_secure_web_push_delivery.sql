-- Timzee browser push: device endpoints and encryption keys are service-only.
-- No browser access to private subscription secrets, even via direct Data API.
CREATE TABLE IF NOT EXISTS public.web_push_subscriptions (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 endpoint_hash text NOT NULL UNIQUE CHECK(length(endpoint_hash)=64),
 endpoint text NOT NULL,
 p256dh text NOT NULL,
 auth_key text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 disabled_at timestamptz
);
CREATE INDEX IF NOT EXISTS web_push_subscriptions_user_active
 ON public.web_push_subscriptions(user_id) WHERE disabled_at IS NULL;
ALTER TABLE public.web_push_subscriptions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.web_push_subscriptions FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.web_push_subscriptions TO service_role;

CREATE TABLE IF NOT EXISTS public.web_push_deliveries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 notification_id uuid NOT NULL REFERENCES public.notifications(id) ON DELETE CASCADE,
 subscription_id uuid NOT NULL REFERENCES public.web_push_subscriptions(id) ON DELETE CASCADE,
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','processing','sent','failed')),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts>=0),
 next_attempt_at timestamptz NOT NULL DEFAULT now(),
 claimed_at timestamptz,
 last_error text,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(notification_id,subscription_id)
);
CREATE INDEX IF NOT EXISTS web_push_due_idx ON public.web_push_deliveries(next_attempt_at,id)
 WHERE status IN ('pending','processing') AND attempts<5;
ALTER TABLE public.web_push_deliveries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.web_push_deliveries FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.web_push_deliveries TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.web_push_deliveries_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.enqueue_web_push_notification()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path=pg_catalog,public AS $push$
BEGIN
 INSERT INTO public.web_push_deliveries(notification_id,subscription_id)
 SELECT NEW.id,s.id FROM public.web_push_subscriptions s
 WHERE s.user_id=NEW.user_id AND s.disabled_at IS NULL
 ON CONFLICT (notification_id,subscription_id) DO NOTHING;
 RETURN NEW;
END $push$;
REVOKE ALL ON FUNCTION public.enqueue_web_push_notification() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS enqueue_web_push_after_notification ON public.notifications;
CREATE TRIGGER enqueue_web_push_after_notification
 AFTER INSERT ON public.notifications FOR EACH ROW
 EXECUTE FUNCTION public.enqueue_web_push_notification();

CREATE OR REPLACE FUNCTION public.claim_web_push_deliveries(p_limit integer DEFAULT 4)
RETURNS TABLE(delivery_id bigint,endpoint text,p256dh text,auth_key text,notification_id uuid,subscription_id uuid,attempts integer)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $claim$
BEGIN
 IF current_setting('request.jwt.claim.role',true) IS DISTINCT FROM 'service_role'
 THEN RAISE EXCEPTION 'forbidden' USING ERRCODE='42501'; END IF;
 RETURN QUERY
 WITH due AS (
   SELECT d.id FROM public.web_push_deliveries d
   JOIN public.web_push_subscriptions s ON s.id=d.subscription_id
   WHERE s.disabled_at IS NULL AND d.attempts<5
     AND ((d.status='pending' AND d.next_attempt_at<=now())
       OR (d.status='processing' AND d.claimed_at<now()-interval '4 minutes'))
   ORDER BY d.next_attempt_at,d.id
   LIMIT LEAST(GREATEST(coalesce(p_limit,1),1),4)
   FOR UPDATE OF d SKIP LOCKED
 ), claimed AS (
   UPDATE public.web_push_deliveries d
   SET status='processing',attempts=d.attempts+1,claimed_at=now()
   FROM due WHERE d.id=due.id
   RETURNING d.id,d.notification_id,d.subscription_id,d.attempts
 )
 SELECT c.id,s.endpoint,s.p256dh,s.auth_key,c.notification_id,c.subscription_id,c.attempts
 FROM claimed c JOIN public.web_push_subscriptions s ON s.id=c.subscription_id;
END $claim$;
REVOKE ALL ON FUNCTION public.claim_web_push_deliveries(integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.claim_web_push_deliveries(integer) TO service_role;

CREATE OR REPLACE FUNCTION public.complete_web_push_delivery(
 p_delivery bigint,p_success boolean,p_permanent boolean DEFAULT false,p_error text DEFAULT NULL
) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER
 SET search_path=pg_catalog,public AS $complete$
DECLARE v_sub uuid;
BEGIN
 IF current_setting('request.jwt.claim.role',true) IS DISTINCT FROM 'service_role'
 THEN RAISE EXCEPTION 'forbidden' USING ERRCODE='42501'; END IF;
 UPDATE public.web_push_deliveries d SET
   status=CASE WHEN p_success THEN 'sent'
       WHEN p_permanent OR d.attempts>=5 THEN 'failed' ELSE 'pending' END,
   next_attempt_at=CASE WHEN p_success OR p_permanent THEN now()
       ELSE now()+(LEAST(3600,power(2,LEAST(d.attempts,6))::integer*60)||' seconds')::interval END,
   claimed_at=NULL,last_error=CASE WHEN p_success THEN NULL ELSE left(coalesce(p_error,'Delivery failed'),180) END
 WHERE d.id=p_delivery AND d.status='processing'
 RETURNING d.subscription_id INTO v_sub;
 IF NOT FOUND THEN RETURN false; END IF;
 IF p_permanent THEN
   UPDATE public.web_push_subscriptions SET disabled_at=now()
   WHERE id=v_sub AND disabled_at IS NULL;
 END IF;
 RETURN true;
END $complete$;
REVOKE ALL ON FUNCTION public.complete_web_push_delivery(bigint,boolean,boolean,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.complete_web_push_delivery(bigint,boolean,boolean,text) TO service_role;
